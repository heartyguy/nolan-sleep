export type MsgKey = keyof typeof en
const DICTS: Record<Lang, typeof en> = { en, zh }

export function t(lang: Lang, key: MsgKey, params?: Record<string, string | number>): string {
  let s: string = DICTS[lang][key] ?? en[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v))
  return s
}

/** relative-time label, language aware */
export function fmtRelL(target: Date, now: Date, lang: Lang): string {
  const m = Math.round((target.getTime() - now.getTime()) / 60_000)
  if (Math.abs(m) <= 1) return lang === 'zh' ? '现在' : 'now'
  const abs = Math.abs(m)
  const txt =
    lang === 'zh'
      ? abs >= 60
        ? `${Math.floor(abs / 60)}小时${abs % 60}分`
        : `${abs}分钟`
      : abs >= 60
        ? `${Math.floor(abs / 60)}h ${abs % 60}m`
        : `${abs}m`
  if (lang === 'zh') return m > 0 ? `${txt}后` : `${txt}前`
  return m > 0 ? `in ${txt}` : `${txt} ago`
}
